use bevy::prelude::*;
use std::collections::VecDeque;
use crate::network::SpacetimeConnection;
use crate::core::NetworkTickTimer;

/// Tracks the client's current simulation tick.
#[derive(Resource, Default)]
pub struct ClientTick(pub u64);

/// Represents a single unit of movement input that has been predicted locally
/// but not yet confirmed by the SpacetimeDB backend.
#[derive(Clone, Debug)]
pub struct BufferedInput {
    pub tick_id: u64,
    pub delta: Vec3,
}

/// Placed on the local player's entity to queue recent movements.
#[derive(Component, Default)]
pub struct InputBuffer {
    pub queue: VecDeque<BufferedInput>,
}

/// Placed on the local player's entity to store the latest verified
/// state received from SpacetimeDB.
#[derive(Component, Default)]
pub struct AuthoritativeState {
    pub position: Vec3,
    pub last_processed_tick: u64,
}

// Architectural Note: Added LocalMovementTracker to capture the net resulting
// positional delta generated by Avian3D's physics step. This decouples our
// network prediction layer from hardcoded WASD logic, inherently supporting
// gravity, collisions, and external forces.
#[derive(Component, Default)]
pub struct LocalMovementTracker {
    pub last_position: Vec3,
}

pub struct PredictionPlugin;

impl Plugin for PredictionPlugin {
    fn build(&self, app: &mut App) {
        app.init_resource::<ClientTick>()
           .add_systems(Update, (
               buffer_and_send_movement,
               reconcile_server_state
           ).chain());
    }
}

// Architectural Note: Replaces the manual WASD translation approach with a 
// robust frame-over-frame physics delta observation. Locked to the 20Hz
// NetworkTickTimer to preserve SpacetimeDB TeV compute economy while maintaining
// highly responsive client prediction.
fn buffer_and_send_movement(
    mut tick: ResMut<ClientTick>,
    mut timer: ResMut<NetworkTickTimer>,
    time: Res<Time>,
    mut query: Query<(&Transform, &mut InputBuffer, &mut LocalMovementTracker), With<AuthoritativeState>>,
    conn: Res<SpacetimeConnection>,
) {
    if !timer.0.tick(time.delta()).just_finished() {
        return;
    }

    for (transform, mut buffer, mut tracker) in query.iter_mut() {
        // Calculate the actual translation applied by the physics engine this tick
        let delta = transform.translation - tracker.last_position;
        
        // Only consume ticks and bandwidth if physical movement actually occurred
        if delta.length_squared() > 0.000001 {
            tick.0 += 1;
            
            // 1. Buffer the action for future reconciliation
            buffer.queue.push_back(BufferedInput {
                tick_id: tick.0,
                delta,
            });
            
            // 2. Fire the authoritative RPC to SpacetimeDB
            let _ = conn.db.reducers.process_movement(tick.0, delta.x, delta.y, delta.z);
            
            // 3. Update the tracker for the next tick calculation
            tracker.last_position = transform.translation;
        }
    }
}

/// Evaluates authoritative state updates from SpacetimeDB against the local buffer.
/// If the client drifted beyond the tolerance radius, forces a rollback and replays inputs.
fn reconcile_server_state(
    mut query: Query<(&mut Transform, &mut InputBuffer, &AuthoritativeState, &mut LocalMovementTracker), Changed<AuthoritativeState>>,
) {
    // Architectural Note: Adjusted to exactly 0.1 meters squared (0.01) to fulfill
    // the strict spatial synchronicity requirement defined in the netcode protocol.
    const TOLERANCE_SQ: f32 = 0.1 * 0.1;

    for (mut transform, mut buffer, auth_state, mut tracker) in query.iter_mut() {
        // 1. Cull Acknowledged Inputs
        // Discard any inputs in our buffer that the server has already computed.
        buffer.queue.retain(|input| input.tick_id > auth_state.last_processed_tick);

        // 2. Re-simulate unacknowledged inputs on top of the true server position
        let mut predicted_pos = auth_state.position;
        for unacked_input in &buffer.queue {
            predicted_pos += unacked_input.delta;
        }

        // 3. Divergence Check
        // If the client's current perceived position differs significantly from 
        // what it *should* be based on authoritative state + pending inputs, we rollback.
        let divergence_sq = transform.translation.distance_squared(predicted_pos);
        
        if divergence_sq > TOLERANCE_SQ {
            // Rollback and instantly snap to the correct predicted position.
            transform.translation = predicted_pos;
            
            // Architectural Note: Crucially, we must also reset the LocalMovementTracker 
            // to prevent the reconciliation snap from being erroneously interpreted as 
            // a massive intentional physical movement on the next frame.
            tracker.last_position = predicted_pos;
            
            tracing::info!(
                "Reconciliation Rollback triggered! Corrected divergence of {:.4} units.", 
                divergence_sq.sqrt()
            );
        }
    }
}